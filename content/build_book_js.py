"""Regenerate dist/book.js from the book structure and quiz files.

Run from the project root after editing content/structure.py or content/quizzes/*.json:
    python3 content/build_book_js.py
Then rebuild the mobile bundle:  cd mobile && npm run build:web

Inputs
  content/structure.py      chapters, sections and page ranges (printed page numbers)
  content/quizzes/<id>.json questions per chapter (3 per section); "concerns" are notes for the author
  content/book-text.txt     text extracted from the book PDF (pdftotext -layout), pages split by form feeds
Page images live in dist/pages/pNNN.webp (900 px wide WebP rendered from the PDF at 150 dpi).
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from structure import CHAPTERS, BOOK  # noqa: E402

FIELDS = ('id', 'section', 'type', 'stem', 'correct', 'rationales', 'clue', 'priority', 'page', 'clientNeed', 'cjmm')
TARGETS = json.load(open(os.path.join(HERE, 'targets.json'), encoding='utf-8'))


def main():
    access = 'full'
    existing = os.path.join(ROOT, 'dist', 'book.js')
    if os.path.exists(existing):  # keep the current BOOK_ACCESS setting
        m = re.search(r"BOOK_ACCESS='(full|preview)'", open(existing, encoding='utf-8').read())
        access = m.group(1) if m else access

    questions, problems = [], []
    for c in CHAPTERS:
        path = os.path.join(HERE, 'quizzes', f"{c['id']}.json")
        data = json.load(open(path, encoding='utf-8'))
        titles = {s[0]: s[1] for s in c['sections']}
        for q in data['questions']:
            if q.get('retired'):
                continue
            missing = [f for f in FIELDS if f not in q]
            if missing or q['section'] not in titles:
                problems.append(f"{c['id']}: {q.get('id')} {missing or 'bad section'}")
                continue
            item = dict(id=q['id'], course=c['id'], section=q['section'], topic=titles[q['section']], type=q['type'],
                        stem=q['stem'], correct=q['correct'], rationales=q['rationales'], clue=q['clue'],
                        priority=q['priority'], page=q['page'], clientNeed=q['clientNeed'], cjmm=q['cjmm'],
                        checked=bool(q.get('checked')), source='book')
            if q['type'] == 'matrix':
                item.update(rows=q['rows'], columns=q['columns'])
            else:
                item['options'] = q['options']
            questions.append(item)
    # Retired ids stay resolvable so saved history keeps working.
    for c in CHAPTERS:
        for q in json.load(open(os.path.join(HERE, 'quizzes', f"{c['id']}.json"), encoding='utf-8'))['questions']:
            if q.get('retired') and q['section'] in {x[0] for x in c['sections']}:
                t = {x[0]: x[1] for x in c['sections']}[q['section']]
                questions.append(dict(id=q['id'], course=c['id'], section=q['section'], topic=t, type=q.get('type', 'mcq'),
                                      stem=q.get('stem', ''), options=q.get('options', []), rows=q.get('rows'), columns=q.get('columns'),
                                      correct=q.get('correct', 0), rationales=q.get('rationales', []), clue=q.get('clue', ''),
                                      priority=q.get('priority', ''), page=q.get('page', 0), clientNeed=q.get('clientNeed', 'pa'),
                                      cjmm=q.get('cjmm', 'analyzeCues'), source='book', retired=True))
    if problems:
        sys.exit('Fix these questions first:\n' + '\n'.join(problems))

    chapters = [dict(id=c['id'], num=c['num'], name=c['name'], short=c['short'], subtitle=c['subtitle'], color=c['color'],
                     tint=c['tint'], pages=c['pages'], opener=c['opener'],
                     sections=[dict(id=s[0], title=s[1], start=s[2], end=s[3]) for s in c['sections']]) for c in CHAPTERS]
    pages = open(os.path.join(HERE, 'book-text.txt'), encoding='utf-8').read().split('\f')
    text = [re.sub(r'\s+', ' ', p).strip() for p in pages[:BOOK['pages']]]
    preview = sorted(set(list(range(1, 15)) + [c['opener'] for c in CHAPTERS] + [c['sections'][0][2] for c in CHAPTERS] + [BOOK['about']]))

    js = ("// Generated by content/build_book_js.py from content/structure.py and content/quizzes/*.json. Do not edit by hand.\n"
          "// BOOK_ACCESS: 'full' shows every page; 'preview' shows only previewPages (see the KDP Select note in README.md).\n"
          f"export const BOOK_ACCESS='{access}';\n"
          f"export const book={json.dumps(dict(BOOK, previewPages=preview))};\n"
          f"export const clientNeeds={json.dumps(TARGETS['categories'])};\n"
          f"export const chapters={json.dumps(chapters, ensure_ascii=False)};\n"
          f"export const bookQuestions={json.dumps(questions, ensure_ascii=False)};\n"
          f"export const pageText={json.dumps(text, ensure_ascii=False)};\n")
    open(existing, 'w', encoding='utf-8').write(js)
    print(f"dist/book.js: {len(chapters)} chapters, {sum(len(c['sections']) for c in chapters)} sections, "
          f"{len(questions)} questions, book access '{access}'")


if __name__ == '__main__':
    main()
