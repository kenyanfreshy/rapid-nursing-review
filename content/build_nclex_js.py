"""Generate dist/nclex.js: the 19 NCLEX topic areas, the imported NurseBound bank and the NGN case studies.

    node content/import_nursebound.mjs <path-to-usrn-pathway-app>   # refresh content/nclex/*.json
    python3 content/build_nclex_js.py
"""
import glob, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

# Topic order, short label and color (ink color on light backgrounds; the app derives tints from it).
TOPICS = [
    ('pharmacology', 'Pharmacology', '#15803d'),
    ('fundamentals', 'Fundamentals & Safety', '#0f766e'),
    ('mental', 'Mental Health', '#7c3aed'),
    ('ethics', 'Ethics & Professional Practice', '#4338ca'),
    ('peds', 'Pediatrics', '#db2777'),
    ('leadership', 'Leadership & Delegation', '#4d7c0f'),
    ('maternal', 'Maternal & Newborn', '#a21caf'),
    ('cardio', 'Cardiovascular', '#dc2626'),
    ('resp', 'Respiratory', '#2563eb'),
    ('neuro', 'Neurological', '#1d4ed8'),
    ('gi', 'Gastrointestinal', '#c2410c'),
    ('fluids', 'Fluids & Electrolytes', '#0369a1'),
    ('immuno', 'Immunology & Infectious Disease', '#9333ea'),
    ('heme', 'Hematology & Oncology', '#be123c'),
    ('endo', 'Endocrine', '#b45309'),
    ('msk', 'Musculoskeletal', '#475569'),
    ('renal', 'Renal & Genitourinary', '#047857'),
    ('shock', 'Multisystem & Shock', '#ea580c'),
    ('integ', 'Integumentary', '#57534e'),
]
BY_NAME = {name: tid for tid, name, _ in TOPICS}


def main():
    bank = json.load(open(os.path.join(HERE, 'nclex', 'bank.json'), encoding='utf-8'))
    cases = json.load(open(os.path.join(HERE, 'nclex', 'ngn.json'), encoding='utf-8'))
    # Book-linked cases written from the book (content/cases/*.json), after the NurseBound ones so the free case stays first.
    for f in sorted(glob.glob(os.path.join(HERE, 'cases', '*.json'))):
        cases += json.load(open(f, encoding='utf-8'))
    # v4 expansion: 700 reviewed questions filling thin NCLEX topics (after the NurseBound items so the free set is unchanged)
    # and 10 more NGN cases. Questions carry APA reference keys from content/nclex/refs.json.
    for f in sorted(glob.glob(os.path.join(HERE, 'nclex', 'v4', '*.json'))):
        if os.path.basename(f) == 'targets.json': continue
        bank += json.load(open(f, encoding='utf-8'))['questions']
    for f in sorted(glob.glob(os.path.join(HERE, 'nclex', 'v4cases', '*.json'))):
        cases += json.load(open(f, encoding='utf-8'))
    refs = json.load(open(os.path.join(HERE, 'nclex', 'refs.json'), encoding='utf-8'))
    unknown = sorted({q['topic'] for q in bank if q['topic'] not in BY_NAME})
    if unknown:
        raise SystemExit(f'Add these topics to TOPICS: {unknown}')
    for q in bank:
        q['nclexTopic'] = BY_NAME[q['topic']]
    topics = [dict(id=t, name=n, color=c) for t, n, c in TOPICS]
    js = ("// Generated by content/build_nclex_js.py from content/nclex/*.json (imported from NurseBound). Do not edit by hand.\n"
          f"export const nclexTopics={json.dumps(topics)};\n"
          f"export const nclexBank={json.dumps(bank, ensure_ascii=False)};\n"
          f"export const ngnCases={json.dumps(cases, ensure_ascii=False)};\n"
          f"export const nclexRefs={json.dumps(refs, ensure_ascii=False)};\n")
    open(os.path.join(ROOT, 'dist', 'nclex.js'), 'w', encoding='utf-8').write(js)
    print(f'dist/nclex.js: {len(topics)} topics, {len(bank)} questions, {len(cases)} NGN cases, {len(js) // 1024} KB')


if __name__ == '__main__':
    main()
