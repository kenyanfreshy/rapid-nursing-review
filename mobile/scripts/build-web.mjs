// Packs the web app in ../dist into an offline bundle for the mobile WebView.
//
//   node scripts/build-web.mjs                 full book (default)
//   BOOK_ACCESS=preview node scripts/build-web.mjs   preview pages only
//
// Output (commit it; EAS uploads only this folder):
//   assets/web/index.html      one file: CSS and all JavaScript inlined (no ES modules,
//                              because module scripts do not load from file:// in WebViews)
//   assets/web/pages/*.webp    book page images (preview mode copies only the preview pages,
//                              so locked pages are not inside the app package at all)
//   assets/web/manifest.js     require() map Metro uses to bundle those files
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const dist = path.resolve(root, '..', 'dist');
const out = path.join(root, 'assets', 'web');
const access = process.env.BOOK_ACCESS === 'preview' ? 'preview' : 'full';

const read = f => fs.readFileSync(path.join(dist, f), 'utf8');
// Turn an ES module into plain statements: drop imports and re-exports, keep declarations.
const unmodule = src => src
  .split('\n')
  .filter(line => !/^\s*import\s.*from\s+['"]/.test(line) && !/^\s*export\s*\{.*\}\s*from\s+['"]/.test(line))
  .join('\n')
  .replace(/^export const /gm, 'const ');

let bookJs = unmodule(read('book.js')).replace(/const BOOK_ACCESS='(full|preview)';/, `const BOOK_ACCESS='${access}';`);
const nclexJs = unmodule(read('nclex.js'));
const dataJs = unmodule(read('data.js'));
// The web preview's "try Pro" switch is never shipped in the app: Pro comes only from RevenueCat.
const appJs = unmodule(read('app.js')).replace('const PREVIEW_UNLOCK = true;', 'const PREVIEW_UNLOCK = false;');
if (!appJs.includes('const PREVIEW_UNLOCK = false;')) throw new Error('PREVIEW_UNLOCK flag not found in app.js');
const script = `(function(){\n'use strict';\n${bookJs}\n${nclexJs}\n${dataJs}\nconst lessons=retiredLessons;\n${appJs}\n})();`;

const html = read('index.html');
const css = read('styles.css');
const themeCss = read('nb-theme.css');
const shell = html
  .replace(/<link rel="stylesheet" href="\.\/styles\.css">/, () => `<style>\n${css}\n</style>`)
  .replace(/<link rel="stylesheet" href="\.\/nb-theme\.css" id="nb-theme">/, () => `<style id="nb-theme">\n${themeCss}\n</style>`)
  .replace(/<link rel="icon"[^>]*>\n?/, '')
  .replace(/<script type="module" src="\.\/app\.js"><\/script>/, () => `<script>\n${script.replace(/<\/script/gi, '<\\/script')}\n</script>`)
  .replace('<meta name="viewport" content="width=device-width, initial-scale=1">',
           '<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">');
if (shell.includes('type="module"') || !shell.includes('<style>') || shell.includes('nb-theme.css">')) throw new Error('index.html did not match the expected shell; update build-web.mjs');

// Which pages ship in the app.
const bookMeta = JSON.parse(read('book.js').match(/export const book=(\{.*?\});/)[1]);
const allPages = Array.from({ length: bookMeta.pages }, (_, i) => i + 1);
const pages = access === 'full' ? allPages : [...new Set(bookMeta.previewPages)].sort((a, b) => a - b);

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(path.join(out, 'pages'), { recursive: true });
fs.writeFileSync(path.join(out, 'index.html'), shell);
const files = ['index.html'];
const copy = name => { fs.copyFileSync(path.join(dist, 'pages', name), path.join(out, 'pages', name)); files.push(`pages/${name}`); };
copy('cover.webp');
for (const p of pages) copy(`p${String(p).padStart(3, '0')}.webp`);

// Version = hash of everything shipped, so the app re-copies files after an update.
const hash = crypto.createHash('sha256');
for (const f of files) hash.update(f).update(fs.readFileSync(path.join(out, f)));
const version = hash.digest('hex').slice(0, 12);

fs.writeFileSync(path.join(out, 'manifest.js'),
`// Generated by scripts/build-web.mjs — do not edit.
export const WEB_VERSION = '${version}';
export const BOOK_ACCESS = '${access}';
export const WEB_FILES = {
${files.map(f => `  '${f}': require('./${f}'),`).join('\n')}
};
`);
const size = files.reduce((n, f) => n + fs.statSync(path.join(out, f)).size, 0);
console.log(`Built assets/web: ${files.length} files, ${(size / 1e6).toFixed(1)} MB, book access: ${access}, version ${version}`);
